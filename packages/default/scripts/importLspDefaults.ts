import { mkdir, readFile, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import path from "node:path";

const sourceFile = process.argv[2]
  ? path.resolve(process.argv[2])
  : path.join(homedir(), "code/the-editor-old/languages.toml");
const outputFile = path.resolve(import.meta.dir, "../src/lsp/generated.ts");

const text = await readFile(sourceFile, "utf8");
const parsed = Bun.TOML.parse(text) as Record<string, unknown>;

const importedLspServers = Object.entries(record(parsed["language-server"]))
  .map(([id, value]) => normalizeServer(id, value))
  .filter((value): value is NonNullable<typeof value> => Boolean(value))
  .sort((a, b) => a.id.localeCompare(b.id));

const importedLspLanguages = array(parsed.language)
  .map(normalizeLanguage)
  .filter((value): value is NonNullable<typeof value> => Boolean(value))
  .sort((a, b) => a.id.localeCompare(b.id));

await mkdir(path.dirname(outputFile), { recursive: true });
await writeFile(outputFile, renderModule(importedLspServers, importedLspLanguages));

console.log(`imported ${importedLspServers.length} LSP servers and ${importedLspLanguages.length} languages from ${sourceFile}`);

function normalizeServer(id: string, value: unknown) {
  const entry = record(value);
  if (typeof entry.command !== "string") return null;
  const args = array(entry.args).filter((item): item is string => typeof item === "string");
  const env = stringRecord(entry.environment);
  return {
    id,
    command: entry.command,
    ...(args.length ? { args } : {}),
    ...(Object.keys(env).length ? { env } : {}),
    ...(entry.config !== undefined ? { initializationOptions: jsonValue(entry.config) } : {}),
  };
}

function normalizeLanguage(value: unknown) {
  const entry = record(value);
  if (typeof entry.name !== "string") return null;
  const fileTypes = array(entry["file-types"])
    .map(normalizeFileType)
    .filter((item): item is string | { glob: string } => Boolean(item));
  const serverIds = array(entry["language-servers"])
    .map(normalizeServerRef)
    .filter((item): item is string => Boolean(item));
  if (!fileTypes.length || !serverIds.length) return null;
  const languageId = typeof entry["language-id"] === "string" ? entry["language-id"] : entry.name;
  return {
    id: entry.name,
    languageId,
    fileTypes,
    serverIds,
  };
}

function normalizeFileType(value: unknown): string | { glob: string } | null {
  if (typeof value === "string") return value;
  const entry = record(value);
  if (typeof entry.glob === "string") return { glob: entry.glob };
  return null;
}

function normalizeServerRef(value: unknown): string | null {
  if (typeof value === "string") return value;
  const entry = record(value);
  return typeof entry.name === "string" ? entry.name : null;
}

function renderModule(servers: unknown[], languages: unknown[]): string {
  return [
    '// @generated by scripts/importLspDefaults.ts — do not edit manually',
    'import type { LspLanguageDefinition, LspServerConfig } from "@the-editor/editor";',
    "",
    `export const importedLspServers = ${JSON.stringify(servers, null, 2)} as LspServerConfig[];`,
    "",
    `export const importedLspLanguages = ${JSON.stringify(languages, null, 2)} as LspLanguageDefinition[];`,
    "",
  ].join("\n");
}

function record(value: unknown): Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value)
    ? value as Record<string, unknown>
    : {};
}

function array(value: unknown): unknown[] {
  return Array.isArray(value) ? value : [];
}

function stringRecord(value: unknown): Record<string, string> {
  return Object.fromEntries(
    Object.entries(record(value)).filter(([, entry]) => typeof entry === "string") as Array<[string, string]>,
  );
}

function jsonValue(value: unknown): unknown {
  return JSON.parse(JSON.stringify(value));
}
